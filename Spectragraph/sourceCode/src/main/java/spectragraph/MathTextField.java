    public void scrollCaretToVisible() {
        if (isInsideScroll)
            return;
        if (!isShowing()) {
            // NOTE (perf): never touch the viewport / geometry while the field is not
            // on screen (happens during drags in a scrolled row); it only queues layouts.
            return;
        }
        isInsideScroll = true;
        try {
            int caret = getCaretPosition();
            Font font = getFont();
            MathLayout layout = ensureLayout(null, font);
            if (layout == null)
                return;

            Insets insets = getInsets();
            int startX = (insets != null ? insets.left : 0) + 2;
            int[] ci = layout.getCaretCoord(null, caret);
            if (ci == null)
                return;
            int caretX = startX + ci[0];

            Component parent = getParent();
            if (parent instanceof javax.swing.JViewport) {
                javax.swing.JViewport vp = (javax.swing.JViewport) parent;
                if (vp.getScrollMode() != javax.swing.JViewport.SIMPLE_SCROLL_MODE) {
                    vp.setScrollMode(javax.swing.JViewport.SIMPLE_SCROLL_MODE);
                }
                int vpWidth = vp.getWidth();
                if (vpWidth <= 0)
                    return;

                int insetsW = (insets != null) ? insets.left + insets.right : 10;
                int contentWidth = layout.totalWidth + insetsW + 10;
                int currentWidth = Math.max(getWidth(), contentWidth);
                if (getWidth() < currentWidth) {
                    setSize(currentWidth, getHeight());
                }

                java.awt.Point vpPos = vp.getViewPosition();
                int currentViewX = vpPos.x;
                int pad = 15;

                int targetX = currentViewX;
                if (caretX + pad > currentViewX + vpWidth) {
                    targetX = caretX + pad - vpWidth;
                } else if (caretX - pad < currentViewX) {
                    targetX = caretX - pad;
                }

                int maxX = Math.max(0, currentWidth - vpWidth);
                targetX = Math.max(0, Math.min(maxX, targetX));

                if (targetX != currentViewX) {
                    vp.setViewPosition(new java.awt.Point(targetX, 0));
                }
            } else {
                Rectangle2D r = modelToView2D(caret);
                if (r != null) {
                    java.awt.Rectangle rect = r.getBounds();
                    rect.x = Math.max(0, rect.x - 15);
                    rect.width += 30;
                    super.scrollRectToVisible(rect);
                }
            }
        } catch (Exception ignored) {
        } finally {
            isInsideScroll = false;
        }
    }

    /**
     * Renders the field with caching. The expensive render pass is performed only
     * when the content, font, size, or selection truly changes. Otherwise the
     * cached
     * image is blitted (O(1)), followed by the caret.
     */
    @Override
    protected void paintComponent(Graphics g) {
        String text = getText();
        if (text == null)
            text = "";

        Font font = getFont();
        Graphics2D g2b = (Graphics2D) g.create();
        g2b.setFont(font);

        MathLayout layout = ensureLayout(g2b, font);
        MathRenderEngine.applyRenderingHints(g2b);

        int w = getWidth();
        int h = getHeight();
        int selStart = getSelectionStart();
        int selEnd = getSelectionEnd();

        boolean cacheMiss = cachedMathImg == null
                || cachedImgW != w
                || cachedImgH != h
                || cachedImgSelStart != selStart
                || cachedImgSelEnd != selEnd
                || !text.equals(cachedImgText)
                || !Objects.equals(font, cachedImgFont);

        // SENZA CACHE TRASPARENTE: il testo si disegna direttamente sul componente,
        // con il fondo gia' dipinto. La cache era un TYPE_INT_ARGB trasparente e i
        // glifi, composti con alpha separata sul fondo, risultavano piu' spessi e
        // sporchi di quelli di un JLabel con lo stesso font (confronto utente:
        // "Analysis Period" nitido, "2*pi" sporco).
        if (false && cacheMiss) {
            if (cachedMathImg == null || cachedMathImg.getWidth() != Math.max(1, w)
                    || cachedMathImg.getHeight() != Math.max(1, h)) {
                cachedMathImg = new BufferedImage(Math.max(1, w), Math.max(1, h), BufferedImage.TYPE_INT_ARGB);
            }
            Graphics2D cg = cachedMathImg.createGraphics();
            cg.setComposite(AlphaComposite.Clear);
            cg.fillRect(0, 0, cachedMathImg.getWidth(), cachedMathImg.getHeight());
            cg.setComposite(AlphaComposite.SrcOver);
            cg.setFont(font);
            MathRenderEngine.applyRenderingHints(cg);
            // SOLO qui, non in applyRenderingHints (che tocca anche il canvas):
            // la cache e' ARGB su fondo scuro, e l'AA in scala di grigi lascia i
            // bordi dei glifi a meta' alpha => grigi sul fondo => testo "slavato".
            // Il subpixel LCD li rende netti. Nessun cambio su STROKE_CONTROL,
            // che era l'altra modifica e forse la causa del rallentamento.
            cg.setRenderingHint(java.awt.RenderingHints.KEY_TEXT_ANTIALIASING,
                    java.awt.RenderingHints.VALUE_TEXT_ANTIALIAS_LCD_HRGB);
            MathRenderEngine.paintFieldWithoutCaret(cg, this, layout);
            cg.dispose();

            cachedImgText = text;
            cachedImgFont = font;
            cachedImgW = w;
            cachedImgH = h;
            cachedImgSelStart = selStart;
            cachedImgSelEnd = selEnd;
        }

        // con opaque=true lo sfondo lo dipinge il campo (nessun ridisegno del parent)
        g2b.setColor(getBackground());
        g2b.fillRect(0, 0, w, h);
        MathRenderEngine.applyBlitHints(g2b);
        MathRenderEngine.paintFieldWithoutCaret(g2b, this, layout);
        // CLIP AGLI INSETS: senza, i segni dell'editor (frazioni, integrali,
        // parentesi alte) uscivano dal riquadro e dipingevano sopra l'etichetta
        // "f(x)" e fuori dal bordo del campo (visto nello screenshot dell'utente).
        java.awt.Insets ti = getInsets();
        java.awt.Shape oldClip = g2b.getClip();
        g2b.clipRect(ti.left, ti.top,
                Math.max(0, w - ti.left - ti.right),
                Math.max(0, h - ti.top - ti.bottom));
        g2b.setClip(oldClip);

        if (fakeCaretVisible) {
            MathRenderEngine.applyRenderingHints(g2b);
            MathRenderEngine.paintCaretOnly(g2b, this, layout, getCaretColor());
        }
        g2b.dispose();
    }

    private IntegralsSuperscript.IntegralRegion findStackingIntegralRegion(String text, int pos) {
        if (text == null || text.isEmpty())
            return null;
        IntegralsSuperscript.IntegralRegion[] integrals = IntegralsSuperscript.findRegions(text);
        if (integrals == null)
            return null;
        for (IntegralsSuperscript.IntegralRegion it : integrals) {
            if (it == null)
                continue;
            java.util.List<IntegralsSuperscript.IntegralSign> signList = (it.signs != null && !it.signs.isEmpty())
                    ? it.signs
                    : java.util.Collections.singletonList(new IntegralsSuperscript.IntegralSign(it.intChar,
                            it.upperOpen, it.upperClose, it.lowerOpen, it.lowerClose));

            boolean hasLimits = false;
            for (IntegralsSuperscript.IntegralSign s : signList) {
                if ((s.upperOpen != -1 && s.upperClose > s.upperOpen + 1)
                        || (s.lowerOpen != -1 && s.lowerClose > s.lowerOpen + 1)) {
                    hasLimits = true;
                    break;
                }
            }

            boolean emptyArg = (it.parenOpen != -1 && it.parenClose != -1
                    && (it.parenClose == it.parenOpen + 1
                            || text.substring(it.parenOpen + 1, it.parenClose).trim().isEmpty()));

            if (it.parenOpen != -1 && pos > it.parenOpen && (it.parenClose == -1 || pos <= it.parenClose)) {
                if (!hasLimits && emptyArg) {
                    return it;
                }
                return null;
            }

            for (IntegralsSuperscript.IntegralSign s : signList) {
                if (pos == s.intChar)
                    return it;
                if (s.upperOpen != -1 && s.upperClose == s.upperOpen + 1 && pos == s.upperOpen + 1)
                    return it;
                if (s.lowerOpen != -1 && s.lowerClose == s.lowerOpen + 1 && pos == s.lowerOpen + 1)
                    return it;
            }
            if (pos == it.intChar)
                return it;

            IntegralsSuperscript.IntegralSign lastSign = signList.get(signList.size() - 1);
            int gapStart = (lastSign.lowerClose != -1 ? lastSign.lowerClose + 1
                    : (lastSign.upperClose != -1 ? lastSign.upperClose + 1 : lastSign.intChar + 1));
            int gapEnd = (it.parenOpen != -1) ? it.parenOpen : gapStart;
            if (pos >= gapStart && pos <= gapEnd) {
                return it;
            }
        }
        return null;
    }

    public static String getNextDifferentials(String currentDiffs, int count) {
        if (count <= 0)
            return "";
        java.util.Set<String> present = new java.util.HashSet<>();
        long maxPedix = 0;
        int len = (currentDiffs != null) ? currentDiffs.length() : 0;
        int i = 0;
        while (i < len) {
            while (i < len && Character.isWhitespace(currentDiffs.charAt(i)))
                i++;
            if (i < len && (currentDiffs.charAt(i) == 'd' || currentDiffs.charAt(i) == 'D')) {
                int start = i;
                i++;
                while (i < len && Character.isLetterOrDigit(currentDiffs.charAt(i)))
                    i++;
                String var = currentDiffs.substring(start, i).toLowerCase();
                present.add(var);
                if (var.startsWith("db") && var.length() > 2) {
                    try {
                        long p = Long.parseLong(var.substring(2));
                        if (p > maxPedix)
                            maxPedix = p;
                    } catch (Exception ignored) {
                    }
                }
            } else {
                i++;
            }
        }

        StringBuilder sb = new StringBuilder(count * 8);
        int added = 0;
        int varIdx = 0;
        while (varIdx < NESTED_DIFF_VARS.length && added < count) {
            String v = NESTED_DIFF_VARS[varIdx++];
            if (!present.contains(v.toLowerCase())) {
                sb.append(" ").append(v);
                present.add(v.toLowerCase());
                added++;
            }
        }
        long pedix = 1;
        while (added < count && pedix <= maxPedix) {
            String cand = "db" + formatDiffPedix(pedix++);
            if (!present.contains(cand.toLowerCase())) {
                sb.append(" ").append(cand);
                present.add(cand.toLowerCase());
                added++;
            }
        }
        while (added < count) {
            sb.append(" db");
            long p = pedix++;
            if (p < 1000000L) {
                sb.append(p);
            } else {
                sb.append("1e").append(6L + (p - 1000000L));
            }
            added++;
        }
        return sb.toString();
    }

