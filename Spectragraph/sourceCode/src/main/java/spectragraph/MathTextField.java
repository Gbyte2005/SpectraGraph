        String text = getText();
        if (text == null || text.isEmpty())
            return 0;

        // NOTE (perf): hit-testing happens on every mouse-dragged event. The old code
        // called getGraphics() (a live, non-antialiased Graphics borrowed from the
        // peer) and only then re-applied the hints; it also created a throw-away
