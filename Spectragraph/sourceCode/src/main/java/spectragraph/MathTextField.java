    @Override
    public void copy() {
        String sel = getSelectedText();
        if (sel == null || sel.isEmpty())
            sel = getText();
        if (sel != null && !sel.isEmpty()) {
            java.awt.datatransfer.StringSelection ss = new java.awt.datatransfer.StringSelection(sel);
            Toolkit.getDefaultToolkit().getSystemClipboard().setContents(ss, ss);
        }
    }

    @Override
    public void paste() {
        try {
            java.awt.datatransfer.Clipboard clip = Toolkit.getDefaultToolkit().getSystemClipboard();
            if (clip.isDataFlavorAvailable(java.awt.datatransfer.DataFlavor.stringFlavor)) {
                String data = (String) clip.getData(java.awt.datatransfer.DataFlavor.stringFlavor);
                if (data != null && !data.isEmpty()) {
                    String norm = MathParser.normalizeForField(data);
                    replaceSelection(norm);
                    return;
                }
            }
        } catch (Exception ignored) {
        }
        super.paste();
    }

    @Override
    public void cut() {
        copy();
        replaceSelection("");
    }

