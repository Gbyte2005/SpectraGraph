    public void triggerDynamicResize() {
        Dimension pref = getPreferredSize();
        Component p = getParent();
        int newW = pref.width;
        int newH = pref.height;
        if (p instanceof javax.swing.JViewport) {
            javax.swing.JViewport vp = (javax.swing.JViewport) p;
            newW = Math.max(vp.getWidth(), pref.width);
        }
        boolean sizeChanged = (getWidth() != newW || getHeight() != newH);
        if (sizeChanged) {
            setSize(newW, newH);
            revalidate();
            Component parent = getParent();
            while (parent != null) {
                if (parent instanceof javax.swing.JScrollPane) {
                    parent.revalidate();
                    Component p2 = parent.getParent();
                    if (p2 != null) {
                        p2.revalidate();
                        Component p3 = p2.getParent();
                        if (p3 != null) {
                            p3.revalidate();
                            Component p4 = p3.getParent();
                            if (p4 != null) {
                                p4.revalidate();
                            }
                        }
                    }
                    break;
                }
                parent = parent.getParent();
            }
        }
        repaint();
        scrollCaretToVisible();
    }

    @Override
    public Dimension getPreferredSize() {
        Dimension d = super.getPreferredSize();
        Font font = getFont();
        int baseH = 34;
        if (font != null) {
            FontMetrics fm = getFontMetrics(font);
            baseH = Math.max(20, fm.getHeight() + 14);
        }

        String text = getText();
        if (text == null || text.isEmpty()) {
            d.height = baseH;
            return d;
        }

        MathLayout layout = ensureLayout(null, font);

        Insets insets = getInsets();
        int insetsW = (insets != null) ? insets.left + insets.right : 10;
        int insetsH = (insets != null) ? insets.top + insets.bottom : 10;
        int mathHeight = layout.maxAscent + layout.maxDescent + insetsH + 16;

        d.height = Math.max(baseH, mathHeight);
        d.width = layout.totalWidth + insetsW + 10;

        return d;
    }

    @Override
    public void setCaretPosition(int position) {
        if (position < 0)
            position = 0;
        if (position > getDocument().getLength())
            position = getDocument().getLength();

        String text = getText();
        if (text != null && !text.isEmpty()) {
            MathLayout layout = ensureLayout(null, getFont());
            position = MathNavigation.getNextAllowedCaret(position, text, layout.fractions, layout.roots, layout.powers,
                    layout.subscripts, layout.integrals, layout.summations, layout.logs, layout.derivatives);
        }
        super.setCaretPosition(position);

        fakeCaretVisible = true;
        // start() solo se fermo: restart() a ogni movimento riarma il blink in
        // continuazione, cioe' un repaint in piu' per ogni evento di trascinamento.
        if (caretTimer != null && !caretTimer.isRunning()) {
            caretTimer.start();
        }
        scrollCaretToVisible();
        Component p = getParent();
        if (p != null) {
            p.repaint();
        } else {
            repaint();
        }
    }

    @Override
    public void moveCaretPosition(int position) {
        int previousDot = getCaret().getDot();
        int previousMark = getCaret().getMark();
        super.moveCaretPosition(position);
        fakeCaretVisible = true;
        // start() solo se fermo: restart() a ogni movimento riarma il blink in
        // continuazione, cioe' un repaint in piu' per ogni evento di trascinamento.
        if (caretTimer != null && !caretTimer.isRunning()) {
            caretTimer.start();
        }

        // NOTE (perf): dragging the caret used to repaint the *parent* (the whole
        // scroll pane / row) on every single mouse event. The field paints itself
        // from its own cached raster, so repainting only the affected strips is
        // enough and keeps dragging at frame rate.
        if (previousDot == getCaret().getDot() && previousMark == getCaret().getMark()) {
            return;
        }
        repaintCaretRegion(previousDot, previousMark);
        scrollCaretToVisible();
    }

    /** Ridisegna solo la striscia del caret: costo O(1) invece di un render del testo. */
    private void repaintCaretOnly() {
        if (!hasFocus() || !isShowing()) {
            return; // senza focus non c'e' caret da disegnare: nessun repaint
        }
        MathLayout layout = ensureLayout(null, getFont());
        int[] ci = (layout != null) ? layout.getCaretCoord(null, getCaretPosition()) : null;
        int width = getWidth();
        int height = getHeight();
        if (ci == null || width <= 0 || height <= 0) {
            repaint();
            return;
        }
        Insets insets = getInsets();
        int startX = (insets != null ? insets.left : 0) + 2;
        int x = startX + ci[0];
        int x0 = Math.max(0, x - 3);
        int x1 = Math.min(width, x + 4);
        repaint(x0, 0, Math.max(1, x1 - x0), height);
    }

    /**
     * Repaints the narrow vertical strips covered by the caret/selection before and
     * after a caret move, instead of the whole component (and never the parent).
     */
    private void repaintCaretRegion(int previousDot, int previousMark) {
        int width = getWidth();
        int height = getHeight();
        if (width <= 0 || height <= 0) {
            repaint();
            return;
        }
        Font font = getFont();
        MathLayout layout = ensureLayout(null, font);
        Insets insets = getInsets();
        int startX = (insets != null ? insets.left : 0) + 2;

        int minX = Integer.MAX_VALUE;
        int maxX = Integer.MIN_VALUE;
        int[] coords = { previousDot, previousMark, getCaretPosition(), getSelectionStart(), getSelectionEnd() };
        for (int c : coords) {
            int[] ci = (layout != null) ? layout.getCaretCoord(null, c) : null;
            if (ci == null)
                continue;
            int x = startX + ci[0];
            if (x < minX)
                minX = x;
            if (x > maxX)
                maxX = x;
        }
        if (minX > maxX) {
            repaint();
            return;
        }
        int x0 = Math.max(0, minX - 3);
        int x1 = Math.min(width, maxX + 4);
        repaint(x0, 0, Math.max(1, x1 - x0), height);
    }

