    private boolean tryEncapsulateComplex(DocumentFilter.FilterBypass fb, int offset, String text, AttributeSet attrs)
            throws BadLocationException {
        if (offset <= 0)
            return false;
        String docText = fb.getDocument().getText(0, fb.getDocument().getLength());
        String sub = docText.substring(0, offset);
        java.util.regex.Matcher m = COMPLEX_TYPING_PATTERN.matcher(sub);
        if (!m.find())
            return false;
        int start = m.start();
        int k = start - 1;
        while (k >= 0 && Character.isWhitespace(sub.charAt(k)))
            k--;
        if (k >= 0 && sub.charAt(k) == '(') {
            return false;
        }
        String suffix = docText.substring(offset);
        java.util.regex.Matcher mExp = java.util.regex.Pattern
                .compile("^\\s*(\\^(?:\\([^)]+\\)|\\{[^}]+\\}|[0-9a-zA-Z]+))").matcher(suffix);
        int expLen = 0;
        String expStr = "";
        if (mExp.find()) {
            expLen = mExp.end();
            expStr = mExp.group(1).trim();
        }
        String content = sub.substring(start) + text + expStr;
        String rep = "(" + content + ")";
        fb.replace(start, (offset - start) + expLen, rep, attrs);
        final int targetCaret = start + 1 + sub.substring(start).length() + text.length();
        setCaretPosition(targetCaret);
        javax.swing.SwingUtilities.invokeLater(() -> setCaretPosition(targetCaret));
        triggerDynamicResize();
        return true;
    }

    private boolean tryEncapsulateComplexInverted(DocumentFilter.FilterBypass fb, int offset, String text,
            AttributeSet attrs)
            throws BadLocationException {
        if (offset <= 0)
            return false;
        String docText = fb.getDocument().getText(0, fb.getDocument().getLength());
        String prefix = docText.substring(0, offset);
        String suffix = docText.substring(offset);

        java.util.regex.Matcher mPre = REAL_END_PATTERN.matcher(prefix);
        if (!mPre.find())
            return false;

        java.util.regex.Matcher mSuff = IMAG_START_PATTERN.matcher(suffix);
        if (!mSuff.find())
            return false;

        int startReal = mPre.start(1);
        String realStr = mPre.group(1);

        int imagEnd = offset + mSuff.end();
        String imagStr = mSuff.group(1).trim();

        int kBefore = startReal - 1;
        while (kBefore >= 0 && Character.isWhitespace(docText.charAt(kBefore)))
            kBefore--;
        int kAfter = imagEnd;
        while (kAfter < docText.length() && Character.isWhitespace(docText.charAt(kAfter)))
            kAfter++;
        if (kBefore >= 0 && docText.charAt(kBefore) == '(' && kAfter < docText.length()
                && docText.charAt(kAfter) == ')') {
            return false;
        }

        String rep = "(" + realStr + " " + text + " " + imagStr + ")";
        fb.replace(startReal, imagEnd - startReal, rep, attrs);
        final int targetCaret = startReal + 1 + realStr.length() + 1 + text.length() + 1;
        setCaretPosition(targetCaret);
        javax.swing.SwingUtilities.invokeLater(() -> setCaretPosition(targetCaret));
        triggerDynamicResize();
        return true;
    }

    private boolean tryStackIntegralWithFilter(DocumentFilter.FilterBypass fb, int pos, AttributeSet attrs)
            throws BadLocationException {
        String docText = fb.getDocument().getText(0, fb.getDocument().getLength());
        IntegralsSuperscript.IntegralRegion it = findStackingIntegralRegion(docText, pos);
        if (it != null) {
            java.util.List<IntegralsSuperscript.IntegralSign> signList = (it.signs != null && !it.signs.isEmpty())
                    ? it.signs
                    : java.util.Collections.singletonList(new IntegralsSuperscript.IntegralSign(it.intChar,
                            it.upperOpen, it.upperClose, it.lowerOpen, it.lowerClose));
            IntegralsSuperscript.IntegralSign lastSign = signList.get(signList.size() - 1);

            int insertSignPos = (it.parenOpen != -1) ? it.parenOpen
                    : (lastSign.lowerClose != -1 ? lastSign.lowerClose + 1
                            : (lastSign.upperClose != -1 ? lastSign.upperClose + 1 : lastSign.intChar + 1));

            boolean hasLimits = false;
            for (IntegralsSuperscript.IntegralSign s : signList) {
                if ((s.upperOpen != -1 && s.upperClose > s.upperOpen + 1)
                        || (s.lowerOpen != -1 && s.lowerClose > s.lowerOpen + 1)) {
                    hasLimits = true;
                    break;
                }
            }
            String signTemplate = hasLimits ? "∫[][]" : "∫";

            String diffs = (it.dxStart != -1 && it.dxEnd <= docText.length()) ? docText.substring(it.dxStart, it.dxEnd)
                    : "";
            String nextDiff = getNextDifferential(diffs);

            int dxEnd = it.dxEnd;
            if (dxEnd != -1) {
                fb.insertString(dxEnd, nextDiff, attrs);
            } else if (it.parenClose != -1) {
                fb.insertString(it.parenClose + 1, "dx" + nextDiff, attrs);
            }

            if (!hasLimits) {
                for (int sIdx = signList.size() - 1; sIdx >= 0; sIdx--) {
                    IntegralsSuperscript.IntegralSign s = signList.get(sIdx);
                    if (s.upperOpen != -1 && s.upperClose == s.upperOpen + 1 && s.lowerOpen != -1
                            && s.lowerClose == s.lowerOpen + 1) {
                        fb.remove(s.upperOpen, 4);
                        if (insertSignPos > s.upperOpen) {
                            insertSignPos -= 4;
                        }
                    }
                }
            }

            fb.insertString(insertSignPos, signTemplate, attrs);

            final int targetCaret;
            if (hasLimits) {
                targetCaret = insertSignPos + 2;
            } else {
                int parenIdx = fb.getDocument().getText(0, fb.getDocument().getLength()).indexOf('(', it.intChar);
                targetCaret = (parenIdx != -1) ? parenIdx + 1 : (insertSignPos + 1);
            }
            setCaretPosition(targetCaret);
            javax.swing.SwingUtilities.invokeLater(() -> setCaretPosition(targetCaret));
            triggerDynamicResize();
            return true;
        }
        return false;
    }

    public static boolean isIntegralText(String text) {
        if (text == null)
            return false;
        String trimmed = text.trim();
        if (trimmed.isEmpty())
            return false;
        if (trimmed.equalsIgnoreCase("int") || trimmed.equalsIgnoreCase("\\int")
                || trimmed.equals("∫") || trimmed.equals("\u222B")) {
            return true;
        }
        if (trimmed.startsWith("∫") || trimmed.startsWith("\u222B")
                || trimmed.toLowerCase().startsWith("\\int") || trimmed.toLowerCase().startsWith("int")) {
            return true;
        }
        return false;
    }

    public static int countIntegralSigns(String text) {
        if (text == null)
            return 0;
        int count = 0;
        for (int i = 0; i < text.length(); i++) {
            char c = text.charAt(i);
            if (c == '∫' || c == '\u222B') {
                count++;
            }
        }
        if (count > 0)
            return count;
        java.util.regex.Matcher m = java.util.regex.Pattern.compile("(?i)(\\\\int|\\bint\\b)").matcher(text);
        while (m.find()) {
            count++;
        }
        return Math.max(count, 1);
    }

    private boolean tryStackPastedIntegral(DocumentFilter.FilterBypass fb, int offset, String text, AttributeSet attrs)
            throws BadLocationException {
        if (!isIntegralText(text))
            return false;
        String docText = fb.getDocument().getText(0, fb.getDocument().getLength());
        IntegralsSuperscript.IntegralRegion it = findStackingIntegralRegion(docText, offset);
        if (it == null)
            return false;

        int signsToStack = countIntegralSigns(text);
        if (signsToStack <= 0)
            signsToStack = 1;

        IntegralsSuperscript.IntegralRegion[] pastedRegions = IntegralsSuperscript.findRegions(text);
        String pastedContent = null;
        if (pastedRegions != null && pastedRegions.length > 0) {
            IntegralsSuperscript.IntegralRegion pReg = pastedRegions[0];
            if (pReg.parenOpen != -1 && pReg.parenClose > pReg.parenOpen + 1) {
                String c = text.substring(pReg.parenOpen + 1, pReg.parenClose).trim();
                if (!c.isEmpty()) {
                    pastedContent = c;
                }
            }
        }

        java.util.List<IntegralsSuperscript.IntegralSign> signList = (it.signs != null && !it.signs.isEmpty())
                ? it.signs
                : java.util.Collections.singletonList(new IntegralsSuperscript.IntegralSign(it.intChar, it.upperOpen,
                        it.upperClose, it.lowerOpen, it.lowerClose));
        IntegralsSuperscript.IntegralSign lastSign = signList.get(signList.size() - 1);

        int insertSignPos = (it.parenOpen != -1) ? it.parenOpen
                : (lastSign.lowerClose != -1 ? lastSign.lowerClose + 1
                        : (lastSign.upperClose != -1 ? lastSign.upperClose + 1 : lastSign.intChar + 1));

        boolean hasLimits = false;
        for (IntegralsSuperscript.IntegralSign s : signList) {
            if ((s.upperOpen != -1 && s.upperClose > s.upperOpen + 1)
                    || (s.lowerOpen != -1 && s.lowerClose > s.lowerOpen + 1)) {
                hasLimits = true;
                break;
            }
        }

        String diffs = (it.dxStart != -1 && it.dxEnd <= docText.length()) ? docText.substring(it.dxStart, it.dxEnd)
                : "";
        String nextDiffs = getNextDifferentials(diffs, signsToStack);

        int dxEnd = it.dxEnd;
        if (dxEnd != -1) {
            fb.insertString(dxEnd, nextDiffs, attrs);
        } else if (it.parenClose != -1) {
            fb.insertString(it.parenClose + 1, "dx" + nextDiffs, attrs);
        }

        if (!hasLimits) {
            for (int sIdx = signList.size() - 1; sIdx >= 0; sIdx--) {
                IntegralsSuperscript.IntegralSign s = signList.get(sIdx);
                if (s.upperOpen != -1 && s.upperClose == s.upperOpen + 1 && s.lowerOpen != -1
                        && s.lowerClose == s.lowerOpen + 1) {
                    fb.remove(s.upperOpen, 4);
                    if (insertSignPos > s.upperOpen) {
                        insertSignPos -= 4;
                    }
                }
            }
        }

        StringBuilder signsTemplate = new StringBuilder();
        String oneSign = hasLimits ? "∫[][]" : "∫";
        for (int i = 0; i < signsToStack; i++) {
            signsTemplate.append(oneSign);
        }
        fb.insertString(insertSignPos, signsTemplate.toString(), attrs);

        if (pastedContent != null) {
            String curDoc = fb.getDocument().getText(0, fb.getDocument().getLength());
            IntegralsSuperscript.IntegralRegion curIt = findStackingIntegralRegion(curDoc,
                    insertSignPos + signsTemplate.length());
            if (curIt == null) {
                IntegralsSuperscript.IntegralRegion[] all = IntegralsSuperscript.findRegions(curDoc);
                if (all != null && all.length > 0)
                    curIt = all[0];
            }
            if (curIt != null && curIt.parenOpen != -1 && curIt.parenClose == curIt.parenOpen + 1) {
                fb.insertString(curIt.parenOpen + 1, pastedContent, attrs);
                final int targetCaret = curIt.parenOpen + 1 + pastedContent.length();
                setCaretPosition(targetCaret);
                javax.swing.SwingUtilities.invokeLater(() -> setCaretPosition(targetCaret));
                triggerDynamicResize();
                return true;
            }
        }

        final int targetCaret;
        if (hasLimits) {
            targetCaret = insertSignPos + 2;
        } else {
            int parenIdx = fb.getDocument().getText(0, fb.getDocument().getLength()).indexOf('(', it.intChar);
            targetCaret = (parenIdx != -1) ? parenIdx + 1 : (insertSignPos + signsTemplate.length());
        }
        setCaretPosition(targetCaret);
        javax.swing.SwingUtilities.invokeLater(() -> setCaretPosition(targetCaret));
        triggerDynamicResize();
        return true;
    }

