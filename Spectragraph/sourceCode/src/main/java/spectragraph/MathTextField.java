    private boolean navigateDown(int caret) {
        MathLayout layout = ensureLayout(null, getFont());
        String docText = getText();

        if (layout.subscripts != null) {
            for (SubscriptsSuperscript.SubscriptRegion s : layout.subscripts) {
                if (s == null)
                    continue;
                if (s.openParen != -1 && caret == s.openParen + 1 && s.closeParen == s.openParen + 1) {
                    try {
                        int pos = s.subChar;
                        getDocument().remove(s.subChar, 3);
                        setCaretPosition(pos);
                        lastRemovedSubscriptCaret = pos;
                        triggerDynamicResize();
                        return true;
                    } catch (Exception ignored) {
                    }
                }
            }
        }

        if (caret == lastRemovedSubscriptCaret) {
            lastRemovedSubscriptCaret = -1;
            return false;
        }
        lastRemovedSubscriptCaret = -1;

        int target = MathNavigation.navigateDown(docText, caret, layout.fractions, layout.roots, layout.powers,
                layout.subscripts, layout.integrals, layout.summations, layout.logs, layout.derivatives);
        if (target != -1) {
            setCaretPosition(target);
            return true;
        }

        if (MathInputHandler.canAddSubscriptAt(docText, caret, layout)) {
            try {
                getDocument().insertString(caret, "_()", null);
                setCaretPosition(caret + 2);
                triggerDynamicResize();
                return true;
            } catch (Exception ignored) {
            }
        }
        if (layout.integrals != null) {
            for (IntegralsSuperscript.IntegralRegion it : layout.integrals) {
                if (it == null)
                    continue;
                if ((caret >= it.intChar && (it.parenOpen == -1 || caret <= it.parenOpen))
                        || (caret > it.parenOpen && caret <= it.parenClose)) {
                    java.util.List<IntegralsSuperscript.IntegralSign> signList = (it.signs != null
                            && !it.signs.isEmpty())
                                    ? it.signs
                                    : java.util.Collections.singletonList(new IntegralsSuperscript.IntegralSign(
                                            it.intChar, it.upperOpen, it.upperClose, it.lowerOpen, it.lowerClose));
                    IntegralsSuperscript.IntegralSign targetSign = MathNavigation.findClosestIntegralSign(signList,
                            caret);
                    if (targetSign != null && targetSign.lowerOpen == -1) {
                        try {
                            int insertPos = targetSign.intChar + 1;
                            getDocument().insertString(insertPos, "[][]", null);
                            setCaretPosition(insertPos + 3);
                            triggerDynamicResize();
                            return true;
                        } catch (Exception ignored) {
                        }
                    }
                }
            }
        }
        return false;
    }

