    private static boolean isIntegralTrigger(javax.swing.text.Document doc, int offset) {
        if (offset < 2)
            return false;
        try {
            if (!doc.getText(offset - 1, 1).equalsIgnoreCase("n"))
                return false;
            if (!doc.getText(offset - 2, 1).equalsIgnoreCase("i"))
                return false;
            int p = offset - 2;
            while (p >= 0 && doc.getText(p, 1).equalsIgnoreCase("i")) {
                p--;
            }
            return (p < 0 || !Character.isLetter(doc.getText(p, 1).charAt(0)));
        } catch (javax.swing.text.BadLocationException e) {
            return false;
        }
    }

